#!/usr/bin/env python3
"""Classify the vector opcodes of src/instructions.in by operand role.

Emits src/rv32_v_class.inc, the table behind rvv_operand_class() in
src/rv32_v_template.c. The shared operand-legality check uses it to apply the
vector register rules of V 1.0 section 5 (v0 as mask, mixed EEW overlap,
mask-destination overlap) without every handler repeating them.

Usage: gen-rvv-classes.py <instructions.in> <output.inc>
"""
import collections
import re
import sys

rows = []
with open(sys.argv[1]) as desc:
    for line in desc:
        line = line.strip()
        if not line or line.startswith(("#", "@")):
            continue
        if not any(f"6..2={op}" in line for op in ("0x15", "0x01", "0x09")):
            continue
        t = line.split()
        # The load and store opcode spaces are shared with the scalar FP ones.
        if re.search(r"6\.\.2=0x0[19]", line) and not t[0].startswith(
            ("vl", "vs")
        ):
            continue
        rows.append((t[0], t[1:]))
VD1, VS11, VS21, VS1S, CMP, MSK, WV, REDW, S1UP, RDD, VST0, WACC, VS31 = [
    1 << i for i in range(13)
]
NAMES = [
    "RVC_VD",
    "RVC_VS1",
    "RVC_VS2",
    "RVC_VS1SRC",
    "RVC_CMP",
    "RVC_MSKGEN",
    "RVC_WV",
    "RVC_REDW",
    "RVC_SLIDE1UP",
    "RVC_RDDEST",
    "RVC_VSTART0",
    "RVC_WACC",
    "RVC_VS3",
]


def classify(n, ops):
    # Every vector load writes data at vd, so a masked one cannot target v0.
    # Segment loads, whole-register loads, and vlm.v are covered too: the
    # latter two are unmasked and never match.
    # An indexed access reads its index group from vs2, which a mask in v0
    # cannot also supply.
    indexed = VS21 if re.search(r"ei\d+_v$", n) and "vs2" in ops else 0
    if re.match(r"^vl", n) and "vd" in ops:
        return VD1 | indexed
    # A store reads its data from vs3, so a masked one cannot take it from v0.
    if re.match(r"^vs", n) and "vs3" in ops:
        return VS31 | indexed
    # A fixed 19..15 or 24..20 field is a sub-opcode, not a register operand.
    has1 = "vs1" in ops and "19..15" not in " ".join(ops)
    has2 = "vs2" in ops and "24..20" not in " ".join(ops)
    vs1_flags = (VS11 | VS1S) if has1 else 0
    hasd = "vd" in ops
    if re.match(r"^vset|^vmv[1248]r_v$", n):
        return 0
    if re.match(r"^vm(and|andn|nand|nor|or|orn|xnor|xor)_mm$", n):
        return 0
    # vcpop.m and vfirst.m, like the mask generators below, require vstart 0.
    if n in ("vcpop_m", "vfirst_m"):
        return VST0
    if n in ("vmv_x_s", "vfmv_f_s", "vcompress_vm"):
        return 0
    # These name the vector destination rd in the descriptor.
    if re.match(r"^vms(bf|if|of)_m$", n):
        return MSK | RDD | VST0
    if n == "viota_m":
        return VD1 | MSK | RDD | VST0
    # With vm=0 these read v0 as a mask (EEW=1), so a data source cannot also
    # be v0: V 1.0 5.2 reserves reading one register at two EEWs.
    if re.match(
        r"^(vm(adc|sbc)_|vms(eq|ne|lt|ltu|le|leu|gt|gtu)_|"
        r"vmf(eq|ne|lt|le|gt|ge)_)",
        n,
    ):
        return CMP | vs1_flags | VS21
    if re.match(r"^v(adc|sbc)_", n):
        return VD1 | VS21 | vs1_flags
    if re.match(r"^v(f?red|f?wred)", n) and n.endswith("_vs"):
        # vd is the scalar result and may be v0; the sources may not.
        return (REDW if re.match(r"^v(f?wred)", n) else 0) | VS11 | VS21
    if (
        re.match(
            r"^(vwadd|vwaddu|vwsub|vwsubu|vfwadd|vfwsub)_w[vx]$|^vn(srl|sra|clip|clipu)_wv$",
            n,
        )
        and has1
    ):
        return WV | VD1 | VS21 | vs1_flags
    if n == "vfslide1up_vf":
        return S1UP | VD1 | VS21
    if n in ("vmv_s_x", "vfmv_s_f"):
        return VD1
    f = (
        (WACC if re.match(r"^(vwmacc|vfw(n?macc|n?msac))", n) else 0)
        | (VD1 if hasd else 0)
        | (VS21 if has2 else 0)
        | vs1_flags
    )
    return f


# Opcodes that need none of the shared checks. Listing them lets a new opcode
# that classify() misses fail the build instead of silently getting no rules.
NO_RULES = re.compile(
    r"^(vset(i?vli|vl)|vmv_x_s|vfmv_f_s|vcompress_vm|vmv[1248]r_v|"
    r"vm(and|andn|nand|nor|or|orn|xnor|xor)_mm)$"
)

cls = collections.OrderedDict()
for n, ops in rows:
    f = classify(n, ops)
    if f:
        cls.setdefault(f, []).append(n)
    elif not NO_RULES.match(n):
        sys.exit(
            "gen-rvv-classes.py: %s has no class; classify or allow it" % n
        )
out = []
out.append(
    "/* Generated by scripts/gen-rvv-classes.py from src/instructions.in."
)
out.append(
    " * Do not edit; rerun the script after changing the vector opcodes."
)
out.append(" */")
for i, nm in enumerate(NAMES):
    out.append("#define %s (1U << %d)" % (nm, i))
out.append("")
out.append("static inline uint32_t rvv_operand_class(uint32_t opcode)")
out.append("{")
out.append("    switch (opcode) {")
for f, names in sorted(cls.items()):
    flags = " | ".join(nm for i, nm in enumerate(NAMES) if f >> i & 1)
    for n in names:
        out.append("    case rv_insn_%s:" % n)
    out.append("        return %s;" % flags)
out.append("    default:")
out.append("        return 0;")
out.append("    }")
out.append("}")
with open(sys.argv[2], "w") as dest:
    dest.write("\n".join(out) + "\n")
